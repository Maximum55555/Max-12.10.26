# 1. Просим ввести строку
text = input("Введите параметры автомобиля по шаблону: ")

# 2. Разбиваем строку по пробелам на список
parts = text.split()  
# 3. Берем первые 4 элемента (индексы с нуля)
mark = parts[0]     # 'LADA'
year = parts[1]     # '2010г'
km = parts[2]       # '205000км'
price = parts[3]    # '450000руб'

# 4. Выводим одной f-строкой с переносами \n
print(f"Продается автомобиль\nМарка: {mark}\nГод выпуска: {year}\nПробег: {km}\nЦена: {price}")
